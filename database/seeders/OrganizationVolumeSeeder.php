<?php

namespace Database\Seeders;

use Illuminate\Database\Seeder;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Str;

/**
 * Multi-tenant volume data: 20 organizations, 100 branches (location groups, 5 per
 * organization) and 5000 users (250 per organization, 50 per branch).
 *
 * Users are linked to branches through locations, so each branch gets one location.
 * Users have no groups (they are listed as clients) and no password (they cannot log in).
 * Every run adds a new, uniquely tagged data set.
 *
 * Usage: php artisan db:seed --class=OrganizationVolumeSeeder
 */
class OrganizationVolumeSeeder extends Seeder
{
    public const ORGANIZATIONS = 20;

    public const BRANCHES = 100;

    public const USERS = 5000;

    // SQL Server allows max 2100 bound parameters per statement.
    private const USER_CHUNK = 150;

    private const PIVOT_CHUNK = 400;

    public function run(): void
    {
        $run = Str::lower(Str::random(6));

        $organizationIds = DB::transaction(fn (): array => $this->seedRun($run));

        $this->command?->info(sprintf(
            'Run "%s": %d organizations (ids: %s), %d branches, %d users.',
            $run, count($organizationIds), implode(', ', $organizationIds), self::BRANCHES, self::USERS,
        ));
    }

    /** @return list<int> */
    private function seedRun(string $run): array
    {
        $now = now();
        $timestamps = ['created_at' => $now, 'updated_at' => $now];
        $faker = fake('ro_RO');
        $description = 'Generated by OrganizationVolumeSeeder';
        $branchesPerOrganization = intdiv(self::BRANCHES, self::ORGANIZATIONS);
        $usersPerBranch = intdiv(self::USERS, self::BRANCHES);

        $organizationIds = [];
        $branchNumber = 0;
        $userNumber = 0;
        $userRows = [];
        $locationIdByEmail = [];

        for ($organization = 1; $organization <= self::ORGANIZATIONS; $organization++) {
            $organizationId = DB::table('organizations')->insertGetId([
                'name' => sprintf('Volum %s Organizatie %02d', $run, $organization),
                'slug' => sprintf('volum-%s-organizatie-%02d', $run, $organization),
                'description' => $description,
                ...$timestamps,
            ]);
            $organizationIds[] = (int) $organizationId;

            for ($branch = 0; $branch < $branchesPerOrganization; $branch++) {
                $branchNumber++;

                $branchId = DB::table('location_groups')->insertGetId([
                    'organization_id' => $organizationId,
                    'name' => sprintf('Volum %s Filiala %03d', $run, $branchNumber),
                    'description' => $description,
                    ...$timestamps,
                ]);

                $locationId = DB::table('locations')->insertGetId([
                    'organization_id' => $organizationId,
                    'location_group_id' => $branchId,
                    // Location names are unique across all organizations.
                    'name' => sprintf('Volum %s Locatie %03d', $run, $branchNumber),
                    'description' => $description,
                    ...$timestamps,
                ]);

                for ($user = 0; $user < $usersPerBranch; $user++) {
                    $userNumber++;
                    $email = "volum.{$run}.{$userNumber}@example.test";
                    $locationIdByEmail[$email] = $locationId;

                    $userRows[] = [
                        'organization_id' => $organizationId,
                        'user_code' => sprintf('V%s%05d', strtoupper($run), $userNumber),
                        'first_name' => $faker->firstName(),
                        'last_name' => $faker->lastName(),
                        'email' => $email,
                        'phone' => sprintf('07000%05d', $userNumber),
                        'active' => true,
                        'password' => null,
                        ...$timestamps,
                    ];
                }
            }
        }

        foreach (array_chunk($userRows, self::USER_CHUNK) as $chunk) {
            DB::table('users')->insert($chunk);
        }

        $pivotRows = DB::table('users')
            ->where('email', 'like', "volum.{$run}.%")
            ->pluck('id', 'email')
            ->map(fn ($userId, string $email): array => [
                'location_id' => $locationIdByEmail[$email],
                'user_id' => $userId,
                ...$timestamps,
            ])
            ->values()
            ->all();

        foreach (array_chunk($pivotRows, self::PIVOT_CHUNK) as $chunk) {
            DB::table('location_user')->insert($chunk);
        }

        return $organizationIds;
    }
}
