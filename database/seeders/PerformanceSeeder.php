<?php

namespace Database\Seeders;

use App\Users\Models\Organization;
use Illuminate\Database\Seeder;
use Illuminate\Support\Facades\DB;
use Illuminate\Support\Facades\Hash;
use Illuminate\Support\Str;
use InvalidArgumentException;

/**
 * Volume data for performance testing: 5000 users, 200 locations,
 * each user attached to 1-3 random locations.
 *
 * Usage: USERS_SEED_ORGANIZATION_ID=1 php artisan db:seed --class=PerformanceSeeder
 */
class PerformanceSeeder extends Seeder
{
    public const USERS = 5000;
    public const LOCATIONS = 200;

    // SQL Server allows max 2100 bound parameters per statement.
    private const USER_CHUNK = 150;
    private const PIVOT_CHUNK = 400;

    public function run(): void
    {
        $organization = $this->organization();
        $now = now();
        $run = Str::lower(Str::random(6));

        $locationIds = DB::transaction(function () use ($organization, $now, $run): array {
            $rows = collect(range(1, self::LOCATIONS))->map(fn (int $i): array => [
                'organization_id' => $organization->id,
                'name' => sprintf('Perf %s Locatie %03d', $run, $i),
                'description' => 'Generated by PerformanceSeeder',
                'created_at' => $now,
                'updated_at' => $now,
            ]);

            foreach ($rows->chunk(self::USER_CHUNK) as $chunk) {
                DB::table('locations')->insert($chunk->values()->all());
            }

            return DB::table('locations')
                ->where('organization_id', $organization->id)
                ->where('name', 'like', "Perf {$run} %")
                ->pluck('id')
                ->all();
        });

        $password = Hash::make('password');
        $faker = fake('ro_RO');

        $userRows = collect(range(1, self::USERS))->map(fn (int $i): array => [
            'organization_id' => $organization->id,
            'user_code' => sprintf('P%s%05d', strtoupper($run), $i),
            'first_name' => $faker->firstName(),
            'last_name' => $faker->lastName(),
            'email' => "perf.{$run}.{$i}@example.test",
            'phone' => sprintf('07%s%05d', substr(crc32($run), 0, 3), $i),
            'active' => true,
            'password' => $password,
            'email_verified_at' => $now,
            'created_at' => $now,
            'updated_at' => $now,
        ]);

        DB::transaction(function () use ($userRows): void {
            foreach ($userRows->chunk(self::USER_CHUNK) as $chunk) {
                DB::table('users')->insert($chunk->values()->all());
            }
        });

        $userIds = DB::table('users')
            ->where('organization_id', $organization->id)
            ->where('email', 'like', "perf.{$run}.%")
            ->pluck('id');

        $pivotRows = $userIds->flatMap(fn (int $userId) => collect($locationIds)
            ->random(random_int(1, 3))
            ->map(fn (int $locationId): array => [
                'location_id' => $locationId,
                'user_id' => $userId,
                'created_at' => $now,
                'updated_at' => $now,
            ]));

        DB::transaction(function () use ($pivotRows): void {
            foreach ($pivotRows->chunk(self::PIVOT_CHUNK) as $chunk) {
                DB::table('location_user')->insert($chunk->values()->all());
            }
        });

        $this->command?->info(sprintf(
            'Run "%s": %d locations, %d users, %d location_user rows in organization %d. Password: "password".',
            $run, count($locationIds), $userIds->count(), $pivotRows->count(), $organization->id,
        ));
    }

    private function organization(): Organization
    {
        $id = env('USERS_SEED_ORGANIZATION_ID');

        if ($id === null || $id === '') {
            throw new InvalidArgumentException('Set USERS_SEED_ORGANIZATION_ID to the target organization id.');
        }

        return Organization::query()->findOrFail((int) $id);
    }
}
